-- READ-ONLY. Produces a schema-only DDL snapshot of production public.* (legacy app) for
-- tests/db/harness/10_legacy_schema.sql. Returns one text column; selects no table data.
with t as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r' and c.relname not like 'cr360_%' and c.relname not like 'nova_%'
)
select string_agg(ddl, E'\n' order by ord) as ddl from (
  select 1 ord, 'create table public.' || quote_ident(t.relname) || ' (' ||
    string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
      case when a.attidentity <> '' then ' generated by default as identity' else '' end ||
      coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '') || case when a.attnotnull then ' not null' else '' end, ', ' order by a.attnum) || ');' ddl
  from t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum group by t.relname
  union all
  select 2, 'alter table public.' || quote_ident(t.relname) || ' add constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';'
  from t join pg_constraint con on con.conrelid = t.oid where con.contype in ('p', 'u', 'c')
  union all
  select 3, 'alter table public.' || quote_ident(t.relname) || ' add constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';'
  from t join pg_constraint con on con.conrelid = t.oid where con.contype = 'f'
  union all
  select 4, pg_get_indexdef(i.indexrelid) || ';' from t join pg_index i on i.indrelid = t.oid
  where not i.indisprimary and not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
  union all
  select 5, pg_get_functiondef(p.oid) || ';' from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and p.proname not like 'cr360_%'
  union all
  select 6, pg_get_triggerdef(tg.oid) || ';' from t join pg_trigger tg on tg.tgrelid = t.oid and not tg.tgisinternal
  union all
  select 7, 'alter table public.' || quote_ident(t.relname) || ' enable row level security;' from t join pg_class c on c.oid = t.oid where c.relrowsecurity
  union all
  select 8, 'create policy ' || quote_ident(policyname) || ' on public.' || quote_ident(tablename) || ' as ' || permissive || ' for ' || cmd || ' to ' || array_to_string(roles, ',') ||
    coalesce(' using (' || qual || ')', '') || coalesce(' with check (' || with_check || ')', '') || ';'
  from pg_policies where schemaname = 'public' and tablename not like 'cr360_%' and tablename not like 'nova_%'
  union all
  select 9, 'create view public.' || quote_ident(viewname) || ' as ' || definition from pg_views where schemaname = 'public'
) x;
